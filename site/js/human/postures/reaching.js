// Posture group "Reaching" (ids reach-*). Standing and seated reaches of one hand or two: forward at shoulder and waist height, forward and up, overhead (one and two
// hands), to the side, across the body, behind the back, to the floor (stooping, squatting, with a side bend), on tiptoe to a shelf, with the foot to a pedal, with a
// step, into a low shelf, over a counter, and the seated reaches (far forward, overhead, to the side, to the floor, behind).
// Each states its target in hints.target ({ description, height_m, distance_m, lateral_m? }: metres for the median man, height above the floor, distance horizontal in
// front of the middle of the feet, or of the hip joints for the seated ones, negative = behind, lateral_m positive to the right) and in hints.prop (a point_marker at
// that height, role "target"; the note gives the whole position), so that reach checks can later be made on any body: the angles are those that reach the target of
// the median man, a smaller body falls short of it by an arm's length difference (the postures are not rescaled).
// How they were made: the legs, the trunk and the neck by hand (the ankles solved so that both soles are flat), the reaching arm by the IK of ik.js to the target,
// rounded to whole degrees, then checked on six bodies (postures.test.mjs) and by eye on contact sheets of the 5th-percentile woman, the median and the
// 95th-percentile man. Semantic tests: tests/human3d/postures-lifting-reaching.test.mjs.
// Each entry is a Posture (typedef in ../pose.js, DESIGN.md 2.4); ../postures.js collects the 13 groups. Rules and checklist for authors:
// docs/human3d/POSTURES.md and POSE.md. Their `category` must be "Reaching"; the usual support is "feet" (or "seat+feet" for the seated reaches).
