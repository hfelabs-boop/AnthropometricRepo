// Posture group "Locomotion" (ids loco-*). Moving on foot, as snapshots: the eight phases of walking (initial contact, loading response, mid-stance, terminal stance,
// pre-swing, initial swing, mid-swing, terminal swing; the right leg is the reference leg, the left leg is 50 percent of the cycle later), the four moments of running
// (foot strike, mid-stance, push-off, flight), the high-step march, stepping up and down a 0.20 m step (three and two phases), stairs up and down with a hand on the
// rail, two phases of climbing a ladder, the jump (crouch, take-off, landing), a side-step and crouch walking.
// Angles: the walking curves are Perry (Gait Analysis, 1992) and Winter (Biomechanics and Motor Control of Human Movement, 4th ed. 2009) values at the instant of each
// phase, rounded: hip 25 / 22 / 2 / -12 / -8 / 10 / 26 / 26 degrees of flexion, knee 4 / 16 / 8 / 8 / 30 / 55 / 28 / 6, ankle 0 / -6 / +6 / +3 / -10 / -8 / 0 / 0 at 0, 12, 31, 45,
// 57, 67, 80 and 93 percent of the cycle (a table of the numbers of the tests); they are approximate (the web pages found disagree by 5 to 10 degrees, and the papers
// were not opened), and the numerical search that follows moved a joint by at most 10 degrees (the figure itself shows how far). The opposite leg is read from the same
// curve 50 percent later, the arms swing against the legs, the pelvis turns a few degrees with the leading leg and the shoulders against it.
// Support and the floor. Every posture is placed by the lowest point of its feet. In the double-support phases (initial contact, loading response, pre-swing) the
// declared contact is the foot that is flat or on its heel; the other foot is tuned to float 3 to 60 mm above the floor for the test bodies (a toe about to leave it), not
// to touch, because the length of two legs cannot be made equal for every body with fixed angles; in the single-support phases the swing foot is high enough to clear.
// All of them are marked hints.dynamic (the balance rule is not applied, they are moments of a movement); the single-support ones are still tuned so that the centre of
// mass is over the supporting foot (a hip adduction of 5 to 8 degrees, a pelvis shift and a spine bend toward it: see the tests). The steps, the stairs and the ladder put
// the second foot on a higher level: the lower foot is on the floor of the posture, and hints.externalSupport says what carries the other one (the step, the tread, the
// rung), hints.prop which catalog type and where. Flight and take-off have no support: a posture is always placed with its lowest foot on the floor, so lift the figure by
// the jump height in a scene.
// Each entry is a Posture (typedef in ../pose.js, DESIGN.md 2.4); ../postures.js collects the 13 groups. Rules and checklist for authors: docs/human3d/POSTURES.md
// and POSE.md. Their `category` must be "Locomotion". Sources are given per entry; "illustrative" means the angles are the author's. Semantic tests:
// tests/human3d/postures-kneeling-locomotion.test.mjs.

