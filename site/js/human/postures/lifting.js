// Posture group "Lifting & carrying" (ids lift-*). Manual handling with a load or a push-pull force: the three techniques of a lift from the floor (squat, stoop and
// semi-squat, each as start, mid and end phase, with a 15 kg crate in the hands), the one-hand lifts (the golfer's lift, a lift with the free hand on the thigh),
// lifts to shoulder height, overhead and to a high shelf, the NIOSH asymmetry family (30 and 60 degrees), the carries (crate in front and at the chest, a load in
// one hand and in both, on the shoulder, a rucksack, the front and rear bearer of a stretcher, the fireman's carry), push (cart, low load), pull (rope) and a
// casualty drag.
// Every phase is a quasi-static snapshot: the load is in the balance check (hints.load) and the support polygon is the soles, so the centre of mass is over the
// feet in all of them. The pushes, the pull and the drag are held up by something else (hints.externalSupport: the cart, the rope, the ground) and are marked dynamic.
// Objects: hints.prop names the catalog type (crate, toolbox, jerrycan, sandbag, rucksack, horizontal_bar as a stand-in for a cart handle or a rope, box), its
// parameters and where it is relative to the middle of the feet (the point half way between the two soles' contact centroid, i.e. the origin of the placement);
// the hands are on the catalog grips (side_left / side_right of a crate, handle of a toolbox or a jerrycan, left / right of a bar), so that the sandbox can put the
// object in the hands and close them with IK.
// How they were made: the legs, the trunk and the neck by hand (the ankles solved so that both soles are flat, the head so that the gaze has the stated elevation),
// the arms by the IK of ik.js to the hand positions of the crate grips, rounded to whole degrees, then checked on six bodies (postures.test.mjs) and by eye on
// contact sheets of the 5th-percentile woman, the median and the 95th-percentile man. Semantic tests: tests/human3d/postures-lifting-reaching.test.mjs.
// Each entry is a Posture (typedef in ../pose.js, DESIGN.md 2.4); ../postures.js collects the 13 groups. Rules and checklist for authors:
// docs/human3d/POSTURES.md and POSE.md. Their `category` must be "Lifting & carrying"; the usual support here is "feet".
