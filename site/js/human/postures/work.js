// Posture group "Work" (ids work-*). Occupational postures and the RULA / REBA reference postures.
// Occupational: standing at a workbench (elbows near 90 degrees) and bent over a low bench, drilling and painting overhead, hammering, pulling a wrench, sawing,
// digging with a shovel, welding in a deep crouch, crouching under a low beam, kneeling at floor level, working from a ladder, pushing up an overhead hatch and
// turning a hatch wheel, seated precision work with the forearms on the desk, looking into a microscope, and working a wrench under a vehicle on a creeper.
// RULA / REBA reference postures (Hignett and McAtamney 2000; McAtamney and Corlett 1993): one standing posture per band of one body segment, everything else
// neutral: trunk 10, 40 and 75 degrees; upper arm 20, 45, 90 and 120 degrees from the trunk; neck 10, 20 and 40 degrees; wrist neutral, flexed and extended 30 degrees.
// Each is solved so that the quantity of metrics.js (trunkInclination, shoulderElevation, neckFlexion, wristFlexion) is the nominal angle on the median man (the
// semantic tests check all three test bodies to a few degrees).
// Objects: hints.prop names the catalog type, its parameters and the grip ids; the note says where it is for the median US Army man, in the placement frame (origin the
// middle of the feet, +Z the way the figure faces, +X the figure's left). The catalog has no saw, torch, roller or microscope: the notes say what stands in for them.
// How they were made: the legs and the trunk by hand or by a numerical search over a few angles (flat feet, centre of mass over the feet on six bodies, the target
// angle), the arms by the inverse kinematics of ik.js to the hand targets (for the median man), then a local search over the arm angles so that the posture is valid
// on all six validator bodies (the heavy man's trunk makes arms in front of the abdomen the hard case), rounded to whole degrees, then looked at on contact sheets of
// the 5th-percentile woman, the median man and the 95th-percentile man. Semantic tests: tests/human3d/postures-work-military.test.mjs.
// Each entry is a Posture (typedef in ../pose.js, DESIGN.md 2.4); ../postures.js collects the 13 groups. Rules and checklist for authors:
// docs/human3d/POSTURES.md and POSE.md. Their `category` must be "Work".
