// hints.props (further objects: the pedals the feet are on, the seat, ...; for pedals `anchors: { R: "accel_pad" }` names the catalog anchor of a foot).
//
// Driver geometry (the car family). Seat back 115 degrees to the pan (a trunk about 23 degrees from the vertical: the SAE design torso angle, and Reed et al.
// 2000, who find that drivers keep the torso almost constant and adapt with the limbs), the pelvis rolled back 6 degrees and the rest of the lean in the
// spine (see sitting.js: more pelvic tilt sinks the buttocks of a heavy body into the seat plane), which puts the hip angle at 110 degrees and the thighs 5
// degrees below the horizontal (hip flexion 79 with the pelvis tilted back 6), the knee at 120 degrees (included angle), the elbows at 107 (10-and-2) to 127
// degrees (9-and-3), the ankle at 85 degrees, the feet on the pedals with the heel on the floor mat (all measured with metrics.js on three bodies).
// The ranges quoted in DRIVER below are those of the brief and of the literature as far as it could be reached (the search found the abstracts of Reed et
// al., Porter and Gyi and the review of Schmidt et al.; the original tables were not opened), so every entry says "illustrative" for its own angles. The seat
// height is the body's popliteal height: real car seats are lower (H30 about 0.27 m above the heel point), which a posture cannot express for all bodies at
// once, so the leg angles are those of a seat at popliteal height (a van, SUV or truck seat). The wheel of the catalog (0.38 m, column 25 degrees from the
// vertical) is placed with its hub 0.34 m above and 0.46 m ahead of the ischial points (0.27 m above and 0.37 m ahead of the hip joint); a hand is fitted to
// it on the median man and the rest is left to IK. Postures with a foot pressed on a pedal (emergency braking, clutch, gear change) declare only the
// resting heel as a contact: with the leg stretched out the heel of the working foot leaves the floor mat, as it does in a car.
// Hands of the added postures (blind-spot check, glovebox, seat adjuster, flight deck, airliner, brace, gunner) were placed by IK on the median man at targets
// given relative to the ischial points, then rounded; on other bodies a hand floats or presses by a few centimetres and the sandbox closes it on the object.
// Sources are named in each entry; "illustrative" means the angles are the author's own. Everything is an indication on a simplified kinematic model.

// Shared literature note of the driver postures.
