// The rig: every joint, its parent, degrees of freedom, ranges of motion, bones and spine regions, plus the joint maths.
// Single source of truth (docs/human3d/DESIGN.md section 1). Pure: imports only three, never touches the DOM.
//
// Conventions in one place. World: +Y up, +Z anterior, +X is the figure's LEFT. At rest every joint frame is world-aligned,
// so the rest offset of a joint is the difference of the neutral joint-centre positions. A joint rotation is
//   q = exp(theta1*axis1 + theta2*axis2) * twist(theta3 about axis3)          (swing-twist, exponential map; twist is innermost)
// so the direction a bone points depends on the swing DOF only. Rotation about +X by +t turns +Y toward +Z, about +Z turns
// +X toward +Y, about +Y turns +Z toward +X. Left joints are written once; the right twin is generated by mirroring:
// axes are pseudovectors ([ax,ay,az] -> [ax,-ay,-az]); probe/moves vectors are polar ([x,y,z] -> [-x,y,z]).
//
// Range-of-motion provenance. The ranges are healthy-adult ACTIVE ranges of the whole joint complex (the shoulder includes
// scapular motion), rounded and in some cases widened by a stated margin so that the posture library can express deep
// squats, kneeling on the heels, cross-legged sitting, overhead reach and full forward bends: this is a posture model for
// design studies, not a clinical tool. Sources: AAOS "Joint Motion" 1965 / Norkin & White "Measurement of Joint Motion",
// Boone & Azen 1979 (J Bone Joint Surg 61A:756), Roach & Miles 1991 (Phys Ther 71:656),
// Kapandji "Physiology of the Joints", White & Panjabi "Clinical Biomechanics of the Spine" 1990,
// Bogduk & Mercer 2000 (Clin Biomech 15:633), Youdas et al. 1992 (Phys Ther 72:770), Ludewig et al. 2009 (J Bone Joint Surg 91A:378).
// Only a few numbers could be cross-checked online while writing this (AAOS hip extension 20 / flexion 120 / abduction 40 /
// adduction 20, knee flexion 135, ankle plantar/dorsiflexion 50/20, shoulder 180/60/180/70/90 from a secondary table; the
// thoracic in-vitro data of Wilke et al. 2017 (PLoS One 12:e0177823: T1-T2 moves most, lower levels about 3-4 degrees of
// flexion-extension) agree with the per-level SHAPE used below). Every number whose provenance could not be checked is
// marked "approx." in its comment and in the `src` string of the DOF. The sources are cited for the typical textbook values
// they report; the values themselves were NOT re-read from the originals.
import * as THREE from "three";

const D2R = Math.PI / 180;
const R2D = 180 / Math.PI;

// ---------------------------------------------------------------------------------------------------------------------
// small helpers
const nz = (x) => (x === 0 ? 0 : x); // turn -0 into 0 so deepEqual/JSON stay tidy
const pseudo = ([x, y, z]) => [nz(x), nz(-y), nz(-z)]; // mirror an axis (pseudovector)
const polar = ([x, y, z]) => [nz(-x), nz(y), nz(z)]; // mirror a position/direction (polar vector)

const X = [1, 0, 0], Y = [0, 1, 0], Z = [0, 0, 1];
const NX = [-1, 0, 0], NY = [0, -1, 0], NZ = [0, 0, -1];

/** Build a DOF record. role: swing1 | swing2 | twist. probe/moves: see DESIGN.md section 1.4 and the test-suite. */
function dof(key, label, role, axis, min, max, probe, moves, pos, neg, src, note) {
  // own copies: X, Y, ... are shared constants and the tables are frozen at the end of the module, but a record must never alias
  const d = { key, label, role, axis: [...axis], min, max, probe: [...probe], moves: [...moves], pos, neg, src };
  if (note) d.note = note;
  return d;
}

export function mirrorId(id) {
  if (id.endsWith("_L")) return id.slice(0, -2) + "_R";
  if (id.endsWith("_R")) return id.slice(0, -2) + "_L";
  return id;
}
export function sideOf(id) {
  return id.endsWith("_L") ? "L" : id.endsWith("_R") ? "R" : null;
}

function mirrorJoint(j) {
  return {
    ...j,
    id: mirrorId(j.id),
    parent: j.parent == null ? null : mirrorId(j.parent),
    label: j.label.replace(/^Left\b/, "Right"),
    side: "R",
    mirrorOf: j.id,
    probe: polar(j.probe),
    dof: j.dof.map((d) => ({ ...d, axis: pseudo(d.axis), probe: polar(d.probe), moves: polar(d.moves) })),
  };
}

