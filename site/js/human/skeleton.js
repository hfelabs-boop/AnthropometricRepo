// Root and region/side expansion
/**
 * Root orientation parameters. `heading` is a world yaw about +Y (+ = turn left); flex / lat / rot are the pelvis's own
 * swing-twist (same axes as any spine joint). q_root = Ry(heading) * swing(flex, lat) * twist(rot). Wide ranges on purpose.
 */
export const ROOT_DOF = [
  { key: "heading", label: "Heading (turn on the spot)", role: "yaw", axis: [0, 1, 0], min: -180, max: 180, pos: "turns to the figure's left", neg: "turns right" },
  ...JOINTS[0].dof.map((d) => ({ ...d })),
];

const ROOT_ANGLES = new Float64Array(3);

const ROOT_KEYS = ["x", "y", "z", "heading", "flex", "lat", "rot"];
/** Throws RangeError unless every present field of a root ({x, y, z, heading, flex, lat, rot}) is a finite number (undefined = 0). */
export function checkRoot(root) {
  for (let i = 0; i < 7; i++) {
    const v = root[ROOT_KEYS[i]];
    if (v !== undefined && (typeof v !== "number" || v - v !== 0)) throw new RangeError(`root.${ROOT_KEYS[i]} is not a finite number`);
  }
}

/** Root quaternion Ry(heading) * exp(swing(flex, lat)) * twist(rot); `root` may omit fields (0); throws RangeError for a non-finite one. */
export function rootQuaternion(root, out = new THREE.Quaternion()) {
  const r = root || {};
  checkRoot(r);
  ROOT_ANGLES[0] = r.flex ?? 0; ROOT_ANGLES[1] = r.lat ?? 0; ROOT_ANGLES[2] = r.rot ?? 0;
  writeJointQuaternion(JOINTS[0], ROOT_ANGLES, SCR, 0);
  const h = 0.5 * (r.heading ?? 0) * D2R, hs = Math.sin(h), hc = Math.cos(h); // (0, hs, 0, hc) * SCR
  const bx = SCR[0], by = SCR[1], bz = SCR[2], bw = SCR[3];
  return out.set(hc * bx + hs * bz, hc * by + hs * bw, hc * bz - hs * bx, hc * bw - hs * by);
}

/**
 * Distribute a region total over its vertebrae (water-filling): shares follow the weights; a level that would leave
 * [lo - add, hi - add] is pinned at its limit and the remainder is re-distributed over the others by their weights.
 * Whatever cannot be placed (all levels at their limit) is dropped.
 */
function distribute(total, w, lo, hi, add) {
  const n = w.length, s = new Array(n).fill(0), fixed = new Array(n).fill(false);
  for (let pass = 0; pass <= n; pass++) {
    let rest = total, wsum = 0;
    for (let i = 0; i < n; i++) (fixed[i] ? (rest -= s[i]) : (wsum += w[i]));
    if (wsum <= 0) break;
    let pinned = false;
    const p = [];
    for (let i = 0; i < n; i++) {
      if (fixed[i]) continue;
      p[i] = (rest * w[i]) / wsum;
      const a = lo[i] - add[i], b = hi[i] - add[i];
      if (p[i] > b + 1e-9) { s[i] = b; fixed[i] = true; pinned = true; }
      else if (p[i] < a - 1e-9) { s[i] = a; fixed[i] = true; pinned = true; }
    }
    if (!pinned) {
      for (let i = 0; i < n; i++) if (!fixed[i]) s[i] = p[i];
      break;
    }
  }
  return s;
}

/**
 * Region totals { lumbar: [flex, lat, rot], thoracic: [...], cervical: [...] } (degrees; missing regions are 0) plus optional
 * per-vertebra additions { L3: [flex, lat, rot], ... } -> { [vertebraId]: [flex, lat, rot] } for all 24 vertebral joints.
 * Each channel is shared by the region weights (weights = flexion/extension, weightsLat, weightsRot); the additions go on top;
 * a vertebra is never pushed beyond its own range: it is pinned and the remainder is re-normalised over the other levels.
 */
export function expandRegions(spine, perVertebra) {
  const sp = spine || {}, pv = perVertebra || {};
  for (const r of Object.keys(sp)) if (!Object.hasOwn(REGIONS, r)) throw new Error(`unknown spine region "${r}"`);
  for (const id of Object.keys(pv)) if (!VERTEBRA_REGION[id]) throw new Error(`unknown vertebra id "${id}"`);
  // a NaN total would spread over every level of the region: refuse it here (same rule as expandSides)
  const check = (what, v) => {
    if (v == null) return;
    if (typeof v.length !== "number") throw new TypeError(`${what}: expected [flex, lat, rot]`);
    for (let i = 0; i < v.length; i++) {
      if (v[i] === undefined && i < 3) continue;
      if (typeof v[i] !== "number" || !Number.isFinite(v[i])) throw new RangeError(`${what}: value ${i} is not a finite number`);
      if (i >= 3 && v[i] !== 0) throw new RangeError(`${what}: expected at most 3 values, got ${v.length}`);
    }
  };
  for (const [r, v] of Object.entries(sp)) check(`spine region "${r}"`, v);
  for (const [id, v] of Object.entries(pv)) check(`vertebra "${id}"`, v);
  const out = {};
  for (const [name, rg] of Object.entries(REGIONS)) {
    const tot = sp[name] || [];
    const js = rg.joints.map((id) => JOINT_BY_ID[id]);
    const rows = rg.joints.map(() => [0, 0, 0]);
    [rg.weights, rg.weightsLat, rg.weightsRot].forEach((w, c) => {
      const lo = js.map((j) => j.dof[c].min), hi = js.map((j) => j.dof[c].max);
      const add = rg.joints.map((id) => pv[id]?.[c] ?? 0);
      const s = distribute(tot[c] ?? 0, w, lo, hi, add);
      rows.forEach((r, i) => { r[c] = nz(s[i] + add[i]); });
    });
    rg.joints.forEach((id, i) => { out[id] = rows[i]; });
  }
  return out;
}

/**
 * The posture `joints` object ("hip_LR", "knee_L", "head", ...) -> one entry per concrete joint id, arrays padded with zeros to
 * the joint's DOF count (the input is not modified). "_LR" means both sides with the same anatomical values; explicit "_L" / "_R"
 * entries override it. Eyes: posture azim + is toward the figure's left for both eyes (DESIGN.md 1.4), converted here to the
 * right eye's lateral-positive joint DOF (azim of eye_R is negated). Unknown ids, "_LR" on unpaired joints, non-numeric values and non-zero values beyond the DOF count throw.
 */
export function expandSides(joints) {
  const out = {};
  const put = (key, id, v) => {
    const j = JOINT_BY_ID[id];
    if (!j) throw new Error(`unknown joint id "${key}"`);
    if (!Array.isArray(v)) throw new Error(`joint "${key}": angles must be an array in DOF order (${j.dof.map((d) => d.key).join(", ")})`);
    const a = j.dof.map((_, i) => v[i] ?? 0);
    for (let i = 0; i < v.length; i++) {
      if (v[i] === undefined) continue; // a hole is 0, as in jointQuaternion / Kinematics.solve
      if (typeof v[i] !== "number" || !Number.isFinite(v[i])) throw new Error(`joint "${key}": value ${i} is not a finite number`);
      if (i >= j.dof.length && v[i] !== 0) throw new Error(`joint "${key}" has ${j.dof.length} DOF (${j.dof.map((d) => d.key).join(", ")}), got ${v.length} values`);
    }
    // posture convention for the eyes (DESIGN.md 1.4): azim + looks toward the figure's LEFT for both eyes; the right eye's joint
    // DOF is lateral-positive (mirror rule), so its sign flips here, for "eye_LR" and an explicit "eye_R" alike
    if (id === "eye_R") a[1] = nz(-a[1]);
    out[id] = a;
  };
  const entries = Object.entries(joints || {});
  for (const [key, v] of entries) { // both sides first, so that explicit sides can override
    if (!key.endsWith("_LR")) continue;
    const base = key.slice(0, -3);
    if (!JOINT_BY_ID[`${base}_L`] || !JOINT_BY_ID[`${base}_R`]) throw new Error(`unknown joint id "${key}"`);
    put(key, `${base}_L`, v);
    put(key, `${base}_R`, v);
  }
  for (const [key, v] of entries) if (!key.endsWith("_LR")) put(key, key, v);
  return out;
}

