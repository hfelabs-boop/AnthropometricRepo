// Spine regions. Per-level SHARES of the motion (relative values after White & Panjabi 1990, "representative" values for
// flexion-extension (combined), lateral bending (one side) and axial rotation (one side); transcribed from the textbook table
// without being able to re-check the book while writing: approx. They are only used as proportions). The absolute whole-region
// ranges below are textbook active ranges of the lumbar / thoracic / cervical spine (AAOS & Norkin-White: lumbar flexion 60,
// extension 25-35, lateral flexion 25; thoracolumbar rotation 30-45 per side, of which the lumbar part is small (about 5-13,
// Kapandji / Gregersen & Lucas 1967, approx.); thoracic flexion about 45, extension about 25 (Kapandji); neck flexion 45-60, extension 55-75,
// lateral flexion 35-45, rotation 70-90 per side (AAOS, Youdas 1992) shared between the cervical region and the occiput-C1
// `head` joint). All these region totals are approx. (textbook values, not re-checked online). Where sources differ I took the mean plus a small margin (extension 35 for the lumbar spine, full forward bend =
// lumbar 60 + thoracic 45 = 105 degrees). Each vertebral joint's own range is share x region range, so the per-level ranges
// add up to the whole-region range (this is what makes the distribution of a region value saturate level by level).
// Joint naming: joint "L4" moves vertebra L4 relative to the one below it (the L4/L5 segment); "L5" is L5/S1; "T12" is T12/L1;
// "C7" is C7/T1; "C1" is C1/C2; "head" is the occiput-C1 joint.
