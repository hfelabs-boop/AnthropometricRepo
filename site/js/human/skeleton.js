// Compiled kernel per joint: coefficients that turn the DOF array (in DOF order, degrees) into the swing vector and the twist
// angle without any lookup. Non-enumerable so the JOINTS data stays plain.
for (const j of JOINTS) {
  const sx = [0, 0, 0], sy = [0, 0, 0], sz = [0, 0, 0], tw = [0, 0, 0];
  let tAxis = null;
  j.dof.forEach((d, i) => {
    if (d.role === "twist") { tw[i] = 1; tAxis = d.axis; }
    else { sx[i] = d.axis[0]; sy[i] = d.axis[1]; sz[i] = d.axis[2]; }
  });
  Object.defineProperty(j, "kernel", {
    value: { sx, sy, sz, tw, tx: tAxis ? tAxis[0] : 0, ty: tAxis ? tAxis[1] : 0, tz: tAxis ? tAxis[2] : 0, hasTwist: !!tAxis, n: j.dof.length },
    enumerable: false,
  });
}

function jointOf(id) {
  const j = JOINT_BY_ID[id];
  if (!j) throw new Error(`unknown joint id "${id}"`);
  return j;
}

/**
 * Allocation-free core of jointQuaternion: writes [x, y, z, w] of exp(swing) * twist into out[o..o+3].
 * `a` holds the joint's angles in DOF order (degrees; missing entries are 0, extra entries are ignored and NOT validated here:
 * hot path, see jointQuaternion / Kinematics.solve for the checked entry points). It takes the array, not three
 * numbers: V8 boxes double arguments of calls it does not inline, which would make Kinematics.solve() allocate.
 */
export function writeJointQuaternion(j, a, out, o = 0) {
  const k = j.kernel;
  // Not `a[0] ?? 0`: the merged value may be undefined, so V8 boxes every double read as a HeapNumber (about 1-3 KB per solve).
  const n0 = a.length, d0 = n0 > 0 ? a[0] : 0, d1 = n0 > 1 ? a[1] : 0, d2 = n0 > 2 ? a[2] : 0;
  const sx = (d0 * k.sx[0] + d1 * k.sx[1] + d2 * k.sx[2]) * D2R;
  const sy = (d0 * k.sy[0] + d1 * k.sy[1] + d2 * k.sy[2]) * D2R;
  const sz = (d0 * k.sz[0] + d1 * k.sz[1] + d2 * k.sz[2]) * D2R;
  const t = 0.5 * (d0 * k.tw[0] + d1 * k.tw[1] + d2 * k.tw[2]) * D2R;
  const n = Math.sqrt(sx * sx + sy * sy + sz * sz);
  const sw = Math.cos(0.5 * n);
  const kk = n < 1e-12 ? 0.5 : Math.sin(0.5 * n) / n; // sin(n/2)/n, limit 1/2
  const ax = sx * kk, ay = sy * kk, az = sz * kk;
  const ts = Math.sin(t);
  const bx = k.tx * ts, by = k.ty * ts, bz = k.tz * ts, bw = Math.cos(t);
  out[o] = sw * bx + bw * ax + (ay * bz - az * by);
  out[o + 1] = sw * by + bw * ay + (az * bx - ax * bz);
  out[o + 2] = sw * bz + bw * az + (ax * by - ay * bx);
  out[o + 3] = sw * bw - (ax * bx + ay * by + az * bz);
}

/** Longest swing rotation vector (degrees) the exponential map represents without wrapping. */
const MAX_SWING = 180;
const SCR = new Float64Array(4);
const NO_ANGLES = Object.freeze([]);
const HOLES = new Float64Array(3); // scratch for angle arrays with holes (max 3 DOF per joint)

/**
 * Validate an angle array for joint `j` (degrees in DOF order) and return the array writeJointQuaternion should read: `a` itself,
 * or `scratch` (a Float64Array of at least 3, zero-filled and then loaded) when `a` has holes (undefined entries count as 0, as in
 * expandSides; a hole beyond the joint's DOF count carries no value and is ignored). Throws RangeError for anything that is not a
 * finite number (strings, booleans, null, NaN, Infinity) and for a non-zero entry beyond the joint's DOF count.
 * Allocation-free on the happy path: Kinematics.solve uses it.
 */
export function checkedAngles(j, a, scratch = HOLES) {
  if (typeof a.length !== "number") throw new TypeError(`angles for "${j.id}" must be an array in DOF order`);
  const nd = j.dof.length, n = a.length;
  let holes = false;
  for (let i = 0; i < n; i++) {
    const v = a[i];
    if (v === undefined) { holes = true; continue; }
    if (typeof v !== "number" || v - v !== 0) throw new RangeError(`joint "${j.id}": angle ${i} is not a finite number`);
    if (i >= nd && v !== 0) throw new RangeError(`joint "${j.id}" has ${nd} DOF (${j.dof.map((d) => d.key).join(", ")}), got ${n} values`);
  }
  if (!holes) return a;
  scratch.fill(0);
  for (let i = 0; i < nd && i < n; i++) if (a[i] !== undefined) scratch[i] = a[i];
  return scratch;
}

/**
 * Local rotation of a joint for `anglesDeg` (array in DOF order; missing entries and holes are 0): q = exp(swing) * twist.
 * Throws for a non-number or non-finite entry and for a non-zero entry beyond the joint's DOF count (the same rule as Kinematics.solve).
 */
export function jointQuaternion(jointId, anglesDeg, out = new THREE.Quaternion()) {
  const j = jointOf(jointId);
  writeJointQuaternion(j, anglesDeg == null ? NO_ANGLES : checkedAngles(j, anglesDeg), SCR, 0);
  return out.set(SCR[0], SCR[1], SCR[2], SCR[3]);
}

/**
 * Inverse of jointQuaternion (principal solution) for the editor's IK. Returns degrees in DOF order. Throws RangeError for a
 * non-finite / non-numeric component (the all-zero quaternion reads as neutral).
 * q = swing * twist is the swing-twist decomposition about the twist axis (if the joint has a twist DOF): the swing is the
 * minimal rotation taking the twist axis to q * axis, its rotation vector is projected on the swing axes. Properties:
 *  - exact round trip for angles whose swing vector has length < 180 degrees and twist in (-180, 180);
 *  - at a swing of exactly 180 degrees (e.g. shoulder flexion 180) the decomposition is not unique; the twist is reported as 0
 *    and the swing keeps the whole rotation, so the quaternion still round-trips but a non-zero twist is folded into the swing
 *    direction. Keep swings below about 179 degrees when the twist matters (see swingLength);
 *  - the corners of the shoulder ROM box have swing vectors LONGER than 180 degrees (e.g. shoulder flex 150 + abd 150 is 212);
 *    jointQuaternion wraps there (the arm points somewhere else) and the inverse returns the equivalent shorter vector, i.e. a
 *    different flexion/abduction pair. clampAngles caps the swing length at 180 so that clamped angles always round-trip;
 *    for raw, unclamped angles inverse(forward(a)) = a only when swingLength() < 180;
 *  - rotation components a joint cannot represent (twist of a joint without a twist DOF, motion about the third axis of a
 *    hinge) are dropped.
 */
export function anglesFromQuaternion(jointId, q, out = []) {
  const j = jointOf(jointId), k = j.kernel;
  let x = q.x, y = q.y, z = q.z, w = q.w;
  // a NaN / missing component would otherwise come out as a silent "neutral" [0, 0, 0] in the editor
  // each component on its own: a sum would overflow to Infinity for finite but huge components (1e308 + 1e308)
  if (!(Number.isFinite(x) && Number.isFinite(y) && Number.isFinite(z) && Number.isFinite(w))) {
    throw new RangeError(`anglesFromQuaternion("${jointId}"): the quaternion must have four finite numeric components`);
  }
  // scale by the largest component first so that squaring cannot overflow (or underflow) in the norm
  const m = Math.max(Math.abs(x), Math.abs(y), Math.abs(z), Math.abs(w)) || 1; // the all-zero quaternion reads as "no rotation"
  x /= m; y /= m; z /= m; w /= m;
  const len = Math.sqrt(x * x + y * y + z * z + w * w);
  x /= len; y /= len; z /= len; w /= len;
  if (w < 0) { x = -x; y = -y; z = -z; w = -w; }
  let tAng = 0;
  let sx = x, sy = y, sz = z, sw = w;
  if (k.hasTwist) {
    const p = x * k.tx + y * k.ty + z * k.tz; // sine part of the twist along its axis
    const n = Math.hypot(w, p);
    if (n > 1e-12) {
      tAng = 2 * Math.atan2(p, w);
      const c = w / n, s = p / n; // swing = q * conj(twist)
      const bx = -s * k.tx, by = -s * k.ty, bz = -s * k.tz;
      sw = w * c - (x * bx + y * by + z * bz);
      sx = w * bx + c * x + (y * bz - z * by);
      sy = w * by + c * y + (z * bx - x * bz);
      sz = w * bz + c * z + (x * by - y * bx);
    }
  }
  const vn = Math.sqrt(sx * sx + sy * sy + sz * sz);
  let rx = 0, ry = 0, rz = 0; // swing rotation vector (radians), length in [0, pi]
  if (vn > 1e-15) {
    const phi = 2 * Math.atan2(vn, Math.max(sw, 0)) / vn;
    rx = sx * phi; ry = sy * phi; rz = sz * phi;
  }
  for (let i = 0; i < j.dof.length; i++) {
    const d = j.dof[i];
    out[i] = nz((d.role === "twist" ? tAng : rx * d.axis[0] + ry * d.axis[1] + rz * d.axis[2]) * R2D + 0);
  }
  if (Array.isArray(out)) out.length = j.dof.length;
  return out;
}

/**
 * Length (degrees) of the swing rotation vector for the given angles (missing angles / holes are 0); > 180 means the principal
 * solution would wrap. Same validation as jointQuaternion.
 */
export function swingLength(jointId, anglesDeg) {
  const j = jointOf(jointId);
  const a = anglesDeg == null ? NO_ANGLES : checkedAngles(j, anglesDeg, new Float64Array(3));
  let s = 0;
  j.dof.forEach((d, i) => { if (d.role !== "twist") s += (a[i] ?? 0) ** 2; });
  return Math.sqrt(s);
}

export function dofKeys(jointId) {
  return jointOf(jointId).dof.map((d) => d.key);
}

/** One zero per DOF for every joint (including the pelvis). */
export function neutralAngles() {
  const o = {};
  for (const j of JOINTS) o[j.id] = j.dof.map(() => 0);
  return o;
}

/**
 * Clamp to the joint's ranges. Missing values are 0, non-finite values become 0; extra values are dropped.
 * Besides the box of each DOF, the swing vector (the swing DOFs together, see swingLength) is capped at 180 degrees: the exponential
 * map wraps beyond it, so a corner of the ROM box such as shoulder flex 150 + abd 150 (length 212) would point the arm somewhere
 * anatomically different and anglesFromQuaternion could not give the pair back. The swing DOFs are scaled by the same factor
 * (towards 0, which stays inside every box) and reported in `clamped`; the twist is not touched.
 */
export function clampAngles(jointId, anglesDeg) {
  const j = jointOf(jointId);
  const angles = [], clamped = [];
  j.dof.forEach((d, i) => {
    const v = Number.isFinite(anglesDeg?.[i]) ? anglesDeg[i] : 0;
    const c = Math.min(d.max, Math.max(d.min, v));
    angles.push(c);
    clamped.push(c !== v || (anglesDeg?.[i] != null && !Number.isFinite(anglesDeg[i])));
  });
  let s = 0;
  j.dof.forEach((d, i) => { if (d.role !== "twist") s += angles[i] * angles[i]; });
  const len = Math.sqrt(s);
  if (len > MAX_SWING) {
    const f = MAX_SWING / len;
    j.dof.forEach((d, i) => {
      if (d.role === "twist" || angles[i] === 0) return;
      angles[i] *= f;
      clamped[i] = true;
    });
  }
  return { angles, clamped };
}

