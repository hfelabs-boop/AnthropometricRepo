const norm = (a) => {
  const s = a.reduce((x, y) => x + y, 0);
  return a.map((v) => v / s);
};

export const REGIONS = {};
const VERTEBRA_REGION = Object.create(null);
for (const [name, r] of Object.entries(SPINE)) {
  const rg = {
    id: name,
    label: r.label,
    joints: [...r.ids],
    weights: norm(r.fe), // flexion-extension distribution; sum 1
    weightsLat: norm(r.lb),
    weightsRot: norm(r.ar),
    range: { flex: [...r.range.flex], lat: [-r.range.lat, r.range.lat], rot: [-r.range.rot, r.range.rot] },
  };
  REGIONS[name] = rg;
  r.ids.forEach((id) => (VERTEBRA_REGION[id] = name));
}

const SPINE_SRC = "White & Panjabi 1990 level shares x AAOS/Kapandji region range (approx.)";
function vertebralDofs(region, i) {
  const rg = REGIONS[region], w = rg.weights[i], wl = rg.weightsLat[i], wr = rg.weightsRot[i];
  const [fmin, fmax] = rg.range.flex;
  return [
    dof("flex", "Flexion / extension", "swing1", X, fmin * w, fmax * w, Y, Z, "forward bend", "extension (backward)", SPINE_SRC),
    dof("lat", "Lateral bend", "swing2", NZ, -rg.range.lat[1] * wl, rg.range.lat[1] * wl, Y, X, "bend to the figure's left", "bend to the right", SPINE_SRC),
    dof("rot", "Axial rotation", "twist", Y, -rg.range.rot[1] * wr, rg.range.rot[1] * wr, Z, X, "turn to the figure's left", "turn to the right", SPINE_SRC),
  ];
}

