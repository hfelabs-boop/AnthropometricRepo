// The joint table. `JOINTS` is ordered parents before children.
const JOINTS = [];
function add(j) {
  JOINTS.push({ side: null, ...j });
  return j;
}
const joint = (id, parent, label, group, probe, dofs, extra) => ({ id, parent, label, group, side: sideOf(id), probe, dof: dofs, ...extra });

