// ---------------------------------------------------------------------------------------------------------------------
// The exported tables are shared by every module: freeze them (deeply) so that no caller can corrupt the rig. The compiled
// kernels are frozen too; their entries are small integers, so reads in the hot path stay unboxed.
function deepFreeze(o) {
  if (o === null || typeof o !== "object" || Object.isFrozen(o)) return o;
  Object.freeze(o);
  for (const v of Object.values(o)) deepFreeze(v);
  return o;
}
for (const j of JOINTS) deepFreeze(j.kernel);
for (const t of [JOINTS, JOINT_BY_ID, CHILDREN, GROUPS, REGIONS, ROOT_DOF, BONES, BONE_BY_ID, BONE_LANDMARKS]) deepFreeze(t);
